HARMONICS = np.array([1.0, 0.50, 0.28, 0.15, 0.08, 0.045, 0.025, 0.014])
HARMONICS = HARMONICS / HARMONICS.sum()

BEATS_PER_BAR = 4.0
TOTAL_BARS = 42


def midi_to_hz(m):
    return 440.0 * 2.0 ** ((m - 69.0) / 12.0)


def organ_tone(freq, dur, sr, amp, brightness=0.8, vibrato=0.0,
               detune_cents=2.5, attack=0.035, release=0.16):
    """Additive pipe-organ tone: soft attack, flat sustain, legato release.

    Two slightly detuned ranks give the gentle chorus of a real organ without
    any percussive transient.
    """
    n = max(8, int(round(dur * sr)))
    t = np.arange(n, dtype=np.float64) / sr

    phase_mod = np.zeros(n, dtype=np.float64)
    if vibrato > 0.0:
        phase_mod = (vibrato / (2.0 * np.pi * 5.0)) * np.sin(2.0 * np.pi * 5.0 * t)

    out = np.zeros(n, dtype=np.float64)
    for rank_detune in (-detune_cents, detune_cents):
        f = freq * 2.0 ** (rank_detune / 1200.0)
        for k, h in enumerate(HARMONICS, start=1):
            partial = brightness if k > 1 else 1.0
            out += h * partial * np.sin(2.0 * np.pi * f * k * t + k * phase_mod)

    env = np.ones(n, dtype=np.float64)
    a = min(n, max(4, int(attack * sr)))
    env[:a] = np.sin(np.linspace(0.0, np.pi / 2.0, a)) ** 2
    r = min(n, max(4, int(release * sr)))
    env[-r:] *= np.cos(np.linspace(0.0, np.pi / 2.0, r)) ** 2

    return (out * env * amp).astype(np.float32)


def add_note(buf, midi, start_s, dur_s, sr, amp, **kw):
    """Mix one note into a stereo buffer, wrapping the tail to the loop head."""
    mono = organ_tone(midi_to_hz(midi), dur_s, sr, amp, **kw)
    start = int(round(start_s * sr))
    n = len(buf)
    idx = (start + np.arange(len(mono))) % n
    np.add.at(buf[:, 0], idx, mono)
    np.add.at(buf[:, 1], idx, mono)


def hall_ir(sr, seconds=2.6, seed=11):
    """Smooth, dark hall impulse response (decorrelated stereo)."""
    rng = np.random.default_rng(seed)
    n = int(seconds * sr)
    t = np.arange(n) / sr
    decay = np.exp(-t * 2.3)
    ir = np.zeros((n, 2), dtype=np.float32)
    for ch in range(2):
        noise = rng.standard_normal(n)
        for _ in range(2):
            noise = np.convolve(noise, [0.25, 0.5, 0.25], mode="same")
        ir[:, ch] = (noise * decay).astype(np.float32)
    ir /= np.sqrt(np.mean(ir ** 2)) + 1e-9
    return ir


def circular_reverb(dry, ir):
    """FFT convolution that wraps the tail to the head — a gapless loop."""
    n = len(dry)
    wet = np.zeros_like(dry)
    for ch in range(2):
        spec = np.fft.rfft(dry[:, ch]) * np.fft.rfft(ir[:, ch], n=n)
        wet[:, ch] = np.fft.irfft(spec, n=n)
    return wet


def render_loop(bars, tempo, sr):
    beat = 60.0 / tempo
    total_beats = bars * BEATS_PER_BAR
    total = total_beats * beat
    n = int(round(total * sr))
    buf = np.zeros((n, 2), dtype=np.float32)

    for start_beat, dur_beat, midi in NOTES:
        if start_beat >= total_beats:
            continue
        start_s = start_beat * beat
        # Legato: hold slightly past the written value so no gap opens between
        # notes, but never so long that the line turns to mush.
        dur_s = (dur_beat * beat) + 0.07
        if dur_s < 0.16:
            dur_s = 0.16
        add_note(buf, midi, start_s, dur_s, sr, 0.085,
                 brightness=0.78, vibrato=0.05, detune_cents=2.5)

        # 16' rank for body on the low notes; 4' sparkle up top.
        if midi <= 52:
            add_note(buf, midi - 12, start_s, dur_s, sr, 0.040,
                     brightness=0.55, detune_cents=1.5)
        if midi >= 64:
            add_note(buf, midi + 12, start_s, dur_s, sr, 0.018,
                     brightness=0.40, detune_cents=1.5)

    wet = circular_reverb(buf, hall_ir(sr))
    mix = buf * 0.72 + wet * 0.34

    mix -= np.mean(mix, axis=0)
    rms = np.sqrt(np.mean(mix ** 2))
    if rms > 1e-9:
        mix = np.tanh(mix * (0.14 / rms)) * 0.90
    return mix


# Speed preset -> number of Prelude bars.  Faster zoom = shorter loop.
# All loops start at bar 1 and are bar-aligned with each other.
LENGTHS = {
    "slow": TOTAL_BARS,   # 0.5x — whole Prelude
    "1x":   32,
    "2x":   16,
    "4x":   8,
}


def main():
    ap = argparse.ArgumentParser(
        description="Render seamless Bach Cello Suite No. 1 Prelude organ loops.")
    ap.add_argument("-o", "--output-dir", default="./sounds/outputs")
    ap.add_argument("-d", "--tempo", type=float, default=70.0,
                    help="quarter-note tempo in BPM (default 70)")
    ap.add_argument("--sr", type=int, default=44100)
    ap.add_argument("--format", default="ogg", choices=["ogg", "wav"])
    args = ap.parse_args()

    os.makedirs(args.output_dir, exist_ok=True)
    for key, bars in LENGTHS.items():
        audio = render_loop(bars, args.tempo, args.sr)
        duration = len(audio) / args.sr
        name = f"bach_cello_prelude_organ_{key}_{duration:.1f}s.{args.format}"
        path = os.path.join(args.output_dir, name)
        if args.format == "ogg":
            # libsndfile's Vorbis encoder segfaults on multi-minute stereo
            # buffers, so render a temporary WAV and hand it to ffmpeg.
            with tempfile.TemporaryDirectory() as tmp:
                wav = os.path.join(tmp, "loop.wav")
                sf.write(wav, audio, args.sr, format="WAV")
                subprocess.run(
                    ["ffmpeg", "-loglevel", "error", "-y", "-i", wav,
                     "-c:a", "libvorbis", "-q:a", "5", path],
                    check=True,
                )
        else:
            sf.write(path, audio, args.sr, format="WAV")
        print(f"  {key:>4}: {bars:2d} bar(s)  {duration:6.1f}s  ->  {path}")


if __name__ == "__main__":
    main()
